export function factOf(n) {
  if (SPECIAL[n]) return SPECIAL[n];
  const tens = Math.floor(n / 10), units = n % 10;
  const parts = [`10이 ${tens}묶음, 1이 ${units}개예요.`];
  parts.push(n % 2 === 0 ? '둘씩 짝지으면 딱 맞는 짝수!' : '둘씩 짝지으면 하나 남는 홀수!');
  if (SQUARES.includes(n)) parts.push('정사각형으로 서 있어요.');
  else if (STAIRS[n]) parts.push('1부터 차례로 더한 계단 모양이에요.');
  return parts.join(' ');
}

// -----------------------------------------------------------
//  친구 목록 1~100 (characters.js 방식과 같은 모양의 정의)
//   type:'numberblock' 은 blocks.js가 registerBuilder로 등록한다
// -----------------------------------------------------------
export const BLOCKS = Array.from({ length: 100 }, (_, i) => {
  const n = i + 1;
  return { id: `nb${n}`, name: String(n), type: 'numberblock', number: n, desc: factOf(n) };
});
export const ME = BLOCKS[99];              // 나 = 100
export const FRIENDS = BLOCKS.slice(0, 99); // 찾아야 할 친구 1~99
export const blockOf = (n) => BLOCKS[n - 1];
