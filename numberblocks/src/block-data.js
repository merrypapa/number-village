// 1~9 색 (0번 칸은 안 쓴다)
export const UNIT_COLORS = [
  0x000000,
  0xe8412c,   // 1 빨강
  0xf7941d,   // 2 주황
  0xfbe323,   // 3 노랑
  0x5bb646,   // 4 초록
  0x4fc3f7,   // 5 하늘
  0x5e4b9c,   // 6 남보라
  0xffffff,   // 7 (무지개 — 블록마다 색이 다르다, 아래 RAINBOW)
  0xe83e8c,   // 8 분홍
  0x8fa3bf,   // 9 회색
];
export const RAINBOW = [0xe8412c, 0xf7941d, 0xfbe323, 0x5bb646, 0x4fc3f7, 0x5e4b9c, 0xb04fd6];
export const RIM_FILL = '#fbfbfb'; // 열 묶음 블록의 안쪽 색 (원작처럼 거의 흰색)

